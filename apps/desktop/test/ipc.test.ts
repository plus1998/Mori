test("guards unknown channels", () => {
  expect(isKnownIpcChannel("app:menu-command")).toBe(true);
  expect(isKnownIpcChannel("workspace:open")).toBe(true);
  expect(isKnownIpcChannel("workspace:open-in-file-manager")).toBe(true);
  expect(isKnownIpcChannel("model-settings:get")).toBe(true);
  expect(isKnownIpcChannel("thread:start")).toBe(true);
  expect(isKnownIpcChannel("composer-draft:save")).toBe(true);
  expect(isKnownIpcChannel("thread:follow-up-enqueue")).toBe(true);
  expect(isKnownIpcChannel("thread:follow-up-escalate")).toBe(true);
  expect(isKnownIpcChannel("terminal:spawn")).toBe(true);
  expect(isKnownIpcChannel("terminal:event")).toBe(true);
  expect(isKnownIpcChannel("storage:get-usage")).toBe(true);
  expect(isKnownIpcChannel("storage:cleanup")).toBe(true);
  expect(isKnownIpcChannel("browser:navigate")).toBe(true);
  expect(isKnownIpcChannel("browser-settings:get")).toBe(true);
  expect(isKnownIpcChannel("unknown")).toBe(false);
});

test("guards terminal stream started events", () => {
  expect(isTerminalStreamEvent({ type: "started", sessionId: "term_1", workspacePath: "/repo" })).toBe(true);
  expect(isTerminalStreamEvent({ type: "started", sessionId: "term_1" })).toBe(false);
});
